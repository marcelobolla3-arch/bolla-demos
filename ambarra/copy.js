export function flatKeys(value, prefix, out) {
  const list = out || [];
  const base = prefix || "";
  if (Array.isArray(value)) return list;
  if (value && typeof value === "object") {
    Object.keys(value).sort().forEach(function (key) {
      flatKeys(value[key], base ? base + "." + key : key, list);
    });
    return list;
  }
  list.push(base);
  return list;
}
